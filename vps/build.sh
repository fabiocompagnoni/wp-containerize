#!/usr/bin/env bash
# Builds the images (wordpress, nginx, edge, vtiger), pushes them to REGISTRY and writes
# images.env with their digests: the only file the VPS needs to know what to run.
# The images hold no site data, so the same images serve every site.
#
# Usage: ./build.sh [--local]
#   --local  no push: images.env points to the local tags (tests on this machine)
set -Eeuo pipefail
shopt -s inherit_errexit   # a failed build inside $(...) stops the script

cd "$(dirname "$0")"
. ./lib.sh

push=1
case "${1:-}" in
    "") ;;
    --local) push=0 ;;
    *) die "usage: $0 [--local]" ;;
esac

# build.local.env (not versioned) overrides build.env, e.g. the real REGISTRY
set -a; . ./build.env; if [ -f build.local.env ]; then . ./build.local.env; fi; set +a
if [ "$push" = 0 ]; then
    REGISTRY=local
elif [[ $REGISTRY == */OWNER ]]; then
    die "set REGISTRY in build.local.env"
fi

tag=$(date -u +%Y%m%d-%H%M)

# build <name> <context> [docker build args...]: prints the reference to use
build() {
    local name=$1 context=$2 image
    shift 2
    image="$REGISTRY/wp-$name:$tag"
    log "building $image"
    docker build --pull -t "$image" "$@" "$context" >&2 || return 1
    if [ "$push" = 0 ]; then echo "$image"; return; fi
    docker push "$image" >&2 || return 1
    docker inspect --format '{{index .RepoDigests 0}}' "$image"
}

wordpress=$(build wordpress ./wordpress \
    --build-arg "WORDPRESS_IMAGE=$WORDPRESS_IMAGE" \
    --build-arg "WP_CLI_VERSION=$WP_CLI_VERSION" \
    --build-arg "WP_CLI_SHA512=$WP_CLI_SHA512" \
    --build-arg "REDIS_CACHE_VERSION=$REDIS_CACHE_VERSION")
nginx=$(build nginx ./nginx --build-arg "NGINX_IMAGE=$NGINX_IMAGE")
edge=$(build edge ./edge --build-arg "NGINX_IMAGE=$NGINX_IMAGE")
vtiger=$(build vtiger ./vtiger --build-arg "VTIGER_PHP_IMAGE=$VTIGER_PHP_IMAGE")

cat > images.env <<EOT
# Generated by build.sh on $(date -u +%FT%TZ): copy it to the VPS next to compose.yaml
WORDPRESS_IMAGE_REF=$wordpress
NGINX_IMAGE_REF=$nginx
EDGE_IMAGE_REF=$edge
VTIGER_IMAGE_REF=$vtiger
MARIADB_IMAGE=$MARIADB_IMAGE
REDIS_IMAGE=$REDIS_IMAGE
MIRROR_IMAGE=$MIRROR_IMAGE
RESTIC_IMAGE=$RESTIC_IMAGE
EOT
log "images.env written"
